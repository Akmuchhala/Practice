package src;

public class Mobile {
    private int cost;
    private String brand;
    private String processor;
    private int storageRAM;
    private int storageROM;

    public int getCost() {
        return cost;
    }

    public void setCost(int cost) {
        this.cost = cost;
    }

    public String getBrand() {
        return brand;
    }

    public void setBrand(String brand) {
        this.brand = brand;
    }

    public String getProcessor() {
        return processor;
    }

    public void setProcessor(String processor) {
        this.processor = processor;
    }

    public int getStorageRAM() {
        return storageRAM;
    }

    public void setStorageRAM(int storageRAM) {
        this.storageRAM = storageRAM;
    }

    public int getStorageROM() {
        return storageROM;
    }

    public void setStorageROM(int storageROM) {
        this.storageROM = storageROM;
    }
}
